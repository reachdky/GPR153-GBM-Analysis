#!/usr/bin/env python3
"""
x04_claims_not_reproduced.py
Write revision/claims_not_reproduced.md from S9 Table (pipeline/x02_claims_ledger.py): every claim of the
submitted manuscript whose value changed, was not reproduced, or was not re-analysed, grouped so that claims whose
reported value could not be located in the original code or outputs are kept apart from claims whose reported
value was located there but is not supported, or is changed, by the revised analysis. Wording is taken from the
S9 Table comparison labels. Reads result files only.

Inputs
  revision/tables/S9_Table.csv
Outputs
  revision/claims_not_reproduced.md

Run from the repository root (after run_all.sh --analysis):
    python pipeline/x04_claims_not_reproduced.py
"""

import pandas as pd

import common

S9 = common.BASE / "tables" / "S9_Table.csv"
OUT = common.BASE / "claims_not_reproduced.md"
NOT_LOCATED = "not located in original code or outputs"
NOT_SUPPORTED = "reported result not reproduced in the revised analysis"
CHANGED = "revised value differs from the reported value"
CONSISTENT = "same direction and significance as reported"
NOT_ANALYSED = "not re-analysed (outside the analysis plan)"
COLS = ["claim", "location in submitted manuscript", "statement", "reported value", "original code or output",
        "original code comparison", "revised value", "revised source"]


def table(d):
    out = ["| " + " | ".join(c.capitalize() for c in COLS) + " |", "|" + "---|" * len(COLS)]
    for _, r in d.iterrows():
        out.append("| " + " | ".join(str(r[c]).replace("|", "\\|").replace("\n", " ") if pd.notna(r[c]) else ""
                                     for c in COLS) + " |")
    return out


def main():
    s = pd.read_csv(S9)
    located = s["original code comparison"] != NOT_LOCATED
    rev = s["revised comparison"]
    groups = [
        ("A. Reported value not located in the original code or outputs",
         "The reported value could not be traced to any script or output available from the original analysis. "
         "The revised analysis is listed for comparison; it is not a re-run of the original computation.",
         s[~located]),
        ("B. Reported value located in the original code or outputs; not reproduced in the revised analysis",
         "The value was found in the original outputs (or follows from the original code), but the revised, "
         "pre-registered analysis does not reproduce the reported result.",
         s[located & (rev == NOT_SUPPORTED)]),
        ("C. Reported value located in the original code or outputs; revised value differs",
         "The value was found in the original outputs (or follows from the original code); the revised analysis "
         "gives a different value.",
         s[located & (rev == CHANGED)]),
        ("D. Reported value located; not re-analysed",
         "No revised analysis exists because the analysis is outside the registered plan.",
         s[located & (rev == NOT_ANALYSED)]),
    ]
    md = ["# Claims of the submitted manuscript that changed, were not reproduced, or were not re-analysed", "",
          f"Generated by `pipeline/x04_claims_not_reproduced.py` from `revision/tables/S9_Table.csv` "
          f"({len(s)} claims; written by `pipeline/x02_claims_ledger.py`). Each claim appears once. Revised values "
          "are from the final analysis run (`revision/verification/final_run.md`). Which claims are removed from "
          "the revised manuscript is an author decision and is not recorded here.", "",
          "## Summary", "",
          "| Original code comparison | " + " | ".join(
              [NOT_SUPPORTED, CHANGED, NOT_ANALYSED, CONSISTENT]) + " | Total |",
          "|---|---|---|---|---|---|"]
    for lab in s["original code comparison"].drop_duplicates():
        sub = s[s["original code comparison"] == lab]
        md.append(f"| {lab} | " + " | ".join(str(int((sub['revised comparison'] == r).sum()))
                                            for r in [NOT_SUPPORTED, CHANGED, NOT_ANALYSED, CONSISTENT])
                  + f" | {len(sub)} |")
    md += ["", "Claims whose reported value was not located (group A) are distinguished from claims contradicted "
           "by the revised analysis (groups B and C): for group A the source of the reported number is unknown; "
           "for groups B and C the original computation is known and the revised analysis differs from it.", ""]
    for title, text, d in groups:
        if not len(d):
            continue
        md += [f"## {title} ({len(d)})", "", text, ""]
        if len(d):
            for lab in [NOT_SUPPORTED, CHANGED, NOT_ANALYSED, CONSISTENT]:
                sub = d[d["revised comparison"] == lab]
                if len(sub) and title.startswith("A."):
                    md += [f"### Revised analysis: {lab} ({len(sub)})", "", *table(sub), ""]
            if not title.startswith("A."):
                md += [*table(d), ""]
    cons = s[rev == CONSISTENT]
    md += [f"## Claims not listed above: {CONSISTENT} ({len(cons)})", "",
           ", ".join(f"{r.claim} ({r.statement})" for r in cons.itertuples()) + ".", ""]
    OUT.write_text("\n".join(md))
    print(f"{OUT}: {len(s) - len(cons)} claims listed, {len(cons)} consistent")


if __name__ == "__main__":
    main()
